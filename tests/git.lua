local fixture = vim.fn.tempname() .. ' git space'
vim.fn.mkdir(fixture, 'p')
local function git(args)
  local cmd = { 'git', '-C', fixture }
  vim.list_extend(cmd, args)
  local result = vim.system(cmd, { text = true, env = { GIT_AUTHOR_NAME = 'Fixture', GIT_AUTHOR_EMAIL = 'fixture@example.invalid', GIT_COMMITTER_NAME = 'Fixture', GIT_COMMITTER_EMAIL = 'fixture@example.invalid' } }):wait(3000)
  assert(result.code == 0, result.stderr)
  return result.stdout
end
git({ 'init', '--quiet' })
local lines = {}
for i = 1, 20 do lines[i] = 'line ' .. i end
vim.fn.writefile(lines, fixture .. '/tracked.txt')
git({ 'add', 'tracked.txt' })
git({ 'commit', '--quiet', '-m', 'Fixture' })
vim.cmd.edit(fixture .. '/tracked.txt')
local gs = require('gitsigns')
assert(vim.wait(5000, function() return vim.b.gitsigns_head ~= nil end, 20), 'Real Git attach')
vim.api.nvim_buf_set_lines(0, 2, 3, false, { 'changed line 3' })
vim.api.nvim_buf_set_lines(0, 15, 16, false, { 'changed line 16' })
vim.api.nvim_exec_autocmds('TextChanged', { buffer = 0 })
assert(vim.wait(3000, function() return #(gs.get_hunks() or {}) == 2 end, 20), 'Two real hunks')
vim.api.nvim_win_set_cursor(0, { 1, 0 })
gs.nav_hunk('next')
assert(vim.wait(1000, function() return vim.api.nvim_win_get_cursor(0)[1] == 3 end), 'Hunk movement')
local windows = #vim.api.nvim_list_wins()
gs.preview_hunk()
assert(vim.wait(1000, function() return #vim.api.nvim_list_wins() > windows end), 'Real hunk preview')
vim.api.nvim_feedkeys(vim.keycode('<Esc>'), 'xt', false)
vim.wait(300)
gs.stage_hunk()
assert(vim.wait(3000, function() return git({ 'diff', '--cached' }):find('changed line 3', 1, true) ~= nil end, 20), 'Stage changes actual index')
git({ 'reset', '--quiet', 'HEAD', '--', 'tracked.txt' })
gs.refresh()
assert(vim.wait(3000, function() return #(gs.get_hunks() or {}) == 2 end, 20), 'External unstage refreshed')
gs.reset_hunk()
assert(vim.wait(3000, function() return vim.api.nvim_buf_get_lines(0, 2, 3, false)[1] == 'line 3' end, 20), 'Reset real hunk')
assert(vim.fn.maparg(']h', 'n') ~= '' and vim.fn.maparg(']c', 'n') == '', 'Hunk key ownership')
vim.fn.mkdir(fixture .. '/nested', 'p')
assert(require('config.terminal').git_root(fixture .. '/nested'):gsub('^/private', '') == fixture:gsub('^/private', ''), 'Git cwd root')
local worktree = fixture .. ' worktree'
git({ 'worktree', 'add', '--quiet', '-b', 'fixture-worktree', worktree })
assert(require('config.terminal').git_root(worktree):gsub('^/private', '') == worktree:gsub('^/private', ''), 'Worktree cwd')
git({ 'worktree', 'remove', '--force', worktree })
vim.fn.delete(fixture, 'rf')
print('PASS: real Gitsigns hunk attach/nav/preview/stage/index/reset, mapping ownership, Git/worktree roots')
vim.cmd('qa!')
